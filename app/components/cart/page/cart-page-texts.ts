export type CartPageTexts = Texts;

export function useCartPageTexts(): CartPageTexts {
  const lang = useLanguage();
  return TEXTS[lang] ?? TEXTS.ES;
}

/** 499 → "499 €", 149.666 → "149,67 €" (sin decimales si el importe es entero). */
export function formatMoney(amount: number, currencyCode: string, locale: string) {
  const isInteger = Math.abs(amount - Math.round(amount)) < 0.005;
  return new Intl.NumberFormat(locale, {
    style: "currency",
    currency: currencyCode,
    minimumFractionDigits: isInteger ? 0 : 2,
    maximumFractionDigits: isInteger ? 0 : 2,
  }).format(amount);
}
